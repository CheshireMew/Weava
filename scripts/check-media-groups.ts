import type { Page } from 'playwright';
import sharp from 'sharp';
import { strict as assert } from 'node:assert';
import { join } from 'node:path';
import { writeFileSync } from 'node:fs';
export async function checkMediaGroups({ origin, api, cli, page, output }: { origin: string; api: (action: string, value?: any) => Promise<any>; cli: (args: string[]) => Promise<any>; page: Page; output: string }) {
  const upload = async (color: string, name: string) => { let job = await api('media', { name, base64: (await sharp({ create: { width: 80, height: 60, channels: 3, background: color } }).png().toBuffer()).toString('base64') }); for (let i = 0; i < 100 && ['queued', 'running'].includes(job.status); i++) { await new Promise((resolve) => setTimeout(resolve, 100)); job = await api('job/' + job.id); } assert.equal(job.status, 'complete'); return job.result; };
  const a = await upload('#ff6200', '分组图一.png'), b = await upload('#0062ff', '分组图二.png');
  await page.goto(origin + '/admin/'); await page.getByRole('button', { name: '媒体', exact: true }).click();
  await page.getByRole('button', { name: '管理分组', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: '媒体分组', exact: true });
  await dialog.getByLabel('分组名称').fill('插图'); await dialog.getByRole('button', { name: '保存分组', exact: true }).click();
  await dialog.getByRole('button', { name: '插图', exact: true }).waitFor(); await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  const group = (await api('media/groups')).find((row: any) => row.value.label === '插图'); assert(group);
  await page.getByLabel('选择 分组图一.png', { exact: true }).check();
  await page.getByLabel('移动所选到分组').selectOption(group.id); await page.getByRole('button', { name: '移动所选', exact: true }).click();
  await page.getByLabel('媒体分组筛选').selectOption(group.id);
  await page.waitForFunction(() => document.querySelectorAll('.media-grid .media-open').length === 1 && document.querySelector('.media-grid')?.getAttribute('aria-busy') === 'false');
  await page.getByRole('button', { name: '分组图一.png', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '分组图二.png', exact: true }).count(), 0);
  assert.equal((await api('media')).find((row: any) => row.id === a.id).value.url, a.value.url);
  await page.getByRole('button', { name: '上传或选择媒体', exact: true }).click();
  dialog = page.getByRole('dialog', { name: '选择媒体', exact: true });
  await dialog.getByLabel('选择器媒体分组').locator('option[value="' + group.id + '"]').waitFor({ state: 'attached' });
  assert.equal(await dialog.getByLabel('选择器媒体分组').inputValue(), group.id);
  await dialog.getByRole('button', { name: '分组图一.png', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.selector-media')?.getAttribute('aria-busy') === 'false');
  assert.equal(await dialog.getByRole('button', { name: '分组图二.png', exact: true }).count(), 0);
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  assert((await cli(['media', 'group', 'list'])).some((row: any) => row.id === group.id));
  const current = (await api('media')).find((row: any) => row.id === a.id), input = join(output, 'move-media.json');
  writeFileSync(input, JSON.stringify({ items: [{ id: current.id, revision: current.revision }], groupId: null })); await cli(['media', 'move', '--input', input]);
  assert.equal((await api('media')).find((row: any) => row.id === a.id).value.groupId, null);
  assert.equal((await fetch(origin + b.value.url)).status, 200);
  await page.getByLabel('媒体分组筛选').selectOption('__ungrouped__');
  await page.getByRole('button', { name: '分组图一.png', exact: true }).waitFor();
  await page.screenshot({ path: join(output, 'media-groups.png'), fullPage: true });
  return { manageGroups: true, atomicMove: true, libraryFilter: true, sharedPickerFilter: true, cliGroupsAndMove: true, originalUrlsUnchanged: true };
}
