import type { BrowserContext, Page } from 'playwright';
import { strict as assert } from 'node:assert';
import { join } from 'node:path';
import { entrySchema } from '@weava/contracts';

export async function checkEditing({ origin, api, page, context, output }: { origin: string; api: (action: string, value?: any) => Promise<any>; page: Page; context: BrowserContext; output: string }) {
  const evidence: Record<string, any> = {};
  const first = await api('entry', { value: entrySchema.parse({ id: 'writer', title: '编辑功能专项', kind: 'content', path: '/writer/', document: { version: 1, format: 'markdown', source: '编辑器正文，链接到官网。' } }), revision: null });
  await page.getByRole('button', { name: '媒体', exact: true }).click();
  await page.locator('.media-open').filter({ hasText: 'studio-image.png' }).click();
  await page.locator('.media-details').getByLabel('名称', { exact: true }).fill('studio-edited.png');
  await page.getByLabel('图片说明', { exact: true }).fill('作品图片说明');
  await page.getByLabel('图注', { exact: true }).fill('原图的图注');
  await page.getByRole('button', { name: '保存媒体信息', exact: true }).click();
  await page.locator('.media-open').filter({ hasText: 'studio-edited.png' }).waitFor();
  assert((await page.locator('.media-details').innerText()).includes('官网页面专项'));
  await page.getByText('裁切副本', { exact: true }).click();
  await page.getByLabel('左边距 %', { exact: true }).fill('25'); await page.getByLabel('上边距 %', { exact: true }).fill('25');
  await page.getByLabel('宽度 %', { exact: true }).fill('50'); await page.getByLabel('高度 %', { exact: true }).fill('50');
  await page.getByRole('button', { name: '生成裁切副本', exact: true }).click();
  await page.locator('.media-open').filter({ hasText: 'studio-edited-crop.png' }).waitFor({ timeout: 30000 });
  const media = (await api('media')).find((row: any) => row.value.name === 'studio-edited-crop.png');
  assert.equal(media.value.width, 400); assert.equal(media.value.height, 225); assert.equal(media.value.alt, '作品图片说明');
  await page.getByLabel('选择 studio-edited.png', { exact: true }).check();
  await page.getByRole('button', { name: '归档所选', exact: true }).click();
  await page.locator('.media-open').filter({ hasText: 'studio-edited.png' }).waitFor({ state: 'hidden' });
  await page.getByLabel('已归档', { exact: true }).check();
  await page.getByLabel('选择 studio-edited.png', { exact: true }).check();
  await page.getByRole('button', { name: '恢复所选', exact: true }).click();
  await page.locator('.media-open').filter({ hasText: 'studio-edited.png' }).waitFor({ state: 'hidden' });
  await page.getByLabel('已归档', { exact: true }).uncheck();
  evidence.media = { metadataSaved: true, crop: [400, 225], archiveAndRestore: true, originalPreserved: (await api('media')).some((row: any) => row.value.name === 'studio-edited.png') };

  const openWriter = async (title: string) => {
    await page.getByRole('button', { name: '内容', exact: true }).click();
    await page.getByLabel('搜索内容').fill(title);
    await page.locator('.entry-list button').filter({ has: page.getByRole('heading', { name: title, exact: true }) }).click();
  };
  await openWriter('编辑功能专项');
  await page.getByRole('button', { name: '可视化编辑', exact: true }).click();
  await page.getByLabel('正文编辑器').locator('p').first().click(); await page.keyboard.press('End');
  await page.getByRole('button', { name: '表格', exact: true }).click();
  await page.locator('.editor-table tr').nth(2).locator('td').last().click();
  await page.keyboard.type('保留的表格内容');
  await page.getByRole('button', { name: '下方加行', exact: true }).click(); assert.equal(await page.locator('.editor-table tr').count(), 4);
  await page.getByRole('button', { name: '右侧加列', exact: true }).click(); assert.equal(await page.locator('.editor-table tr').first().locator('th,td').count(), 4);
  await page.getByRole('button', { name: '移除列', exact: true }).click();
  await page.getByRole('button', { name: '移除行', exact: true }).click();
  assert.equal(await page.locator('.editor-table tr').count(), 3); assert.equal(await page.locator('.editor-table tr').first().locator('th,td').count(), 3);
  await page.getByRole('button', { name: 'Markdown', exact: true }).click();
  assert((await page.getByLabel('正文源码').inputValue()).includes('保留的表格内容'));
  await page.getByRole('button', { name: '可视化编辑', exact: true }).click();
  assert.equal(await page.locator('.editor-table tr').count(), 3);
  await page.getByLabel('正文编辑器').locator('p').last().click(); await page.keyboard.press('Control+End');
  await page.getByRole('button', { name: '插入媒体', exact: true }).click();
  await page.locator('dialog').getByRole('button', { name: 'studio-edited-crop.png', exact: true }).click();
  await page.getByRole('button', { name: '编辑媒体', exact: true }).click();
  await page.locator('.media-inline-settings').getByLabel('图注', { exact: true }).fill('文章媒体的独立图注');
  await page.getByRole('button', { name: '保存媒体修改', exact: true }).click();
  await page.getByLabel('正文编辑器').locator('p').first().evaluate((element) => { const range = document.createRange(); range.selectNodeContents(element); window.getSelection()!.removeAllRanges(); window.getSelection()!.addRange(range); });
  await page.getByRole('button', { name: '链接', exact: true }).click();
  await page.getByRole('button', { name: '链接到内容', exact: true }).click();
  await page.getByLabel('查找内容').fill('官网页面专项');
  await page.locator('dialog').getByRole('button', { name: '官网页面专项 /studio/', exact: true }).click();
  await page.getByRole('button', { name: '发布', exact: true }).click();
  await page.getByRole('heading', { name: '发布变更', exact: true }).waitFor();
  await page.getByRole('button', { name: '确认发布', exact: true }).click();
  await page.getByRole('heading', { name: '发布变更', exact: true }).waitFor({ state: 'hidden', timeout: 30000 });
  const visitor = await context.newPage(); await visitor.goto(origin + '/writer/');
  assert.equal(await visitor.locator('main table tr').count(), 3);
  assert((await visitor.locator('main').innerText()).includes('保留的表格内容'));
  assert((await visitor.locator('main').innerText()).includes('文章媒体的独立图注'));
  assert.equal(await visitor.locator('main a[href="/studio/"]').count(), 1);
  await visitor.screenshot({ path: join(output, 'rich-editor-published.png'), fullPage: true });
  evidence.richText = { tableRowsAndColumns: true, markdownTableRoundTrip: true, mediaCaption: true, stableContentLink: true };

  const base = await api('entry/writer');
  await api('entry', { value: { ...base.value, title: '另一个窗口的标题' }, revision: base.revision });
  await page.getByLabel('内容标题').fill('保留本地标题'); await page.getByLabel('内容摘要').fill('本地窗口的摘要');
  await page.getByRole('dialog', { name: '解决保存冲突', exact: true }).waitFor();
  assert(await page.evaluate(() => !!localStorage.getItem('weava-draft:writer')));
  await page.screenshot({ path: join(output, 'edit-conflict.png'), fullPage: true });
  // Reopen the browser's preserved draft after reloading, then resolve it against the current server version.
  await page.reload(); await openWriter('另一个窗口的标题');
  await page.getByRole('button', { name: '恢复到编辑器', exact: true }).click();
  await page.getByLabel('标题保留本地', { exact: true }).check();
  await page.getByRole('button', { name: '保存合并结果', exact: true }).click();
  await page.getByRole('dialog', { name: '解决保存冲突', exact: true }).waitFor({ state: 'hidden' });
  const merged = await api('entry/writer'); assert.equal(merged.value.title, '保留本地标题'); assert.equal(merged.value.description, '本地窗口的摘要');
  await visitor.reload(); assert.equal(await visitor.getByRole('heading', { level: 1 }).innerText(), '编辑功能专项');
  evidence.conflictRecovery = { staleWindowDetected: true, browserDraftSurvivesReload: true, explicitChoiceSaved: true, disjointChangesMerged: true, publicationUntouched: true };
  await page.getByRole('button', { name: '历史版本', exact: true }).click();
  await page.getByLabel('目标版本', { exact: true }).selectOption(String(first.revision));
  await page.getByLabel('修改后 标题', { exact: true }).waitFor();
  await page.screenshot({ path: join(output, 'revision-comparison.png'), fullPage: true });
  await page.getByRole('button', { name: '查看页面对照', exact: true }).click();
  await page.frameLocator('iframe[title="目标版本预览"]').getByRole('heading', { name: '编辑功能专项', exact: true }).waitFor();
  await page.getByRole('button', { name: '将目标版本恢复为工作稿', exact: true }).click();
  await page.getByRole('dialog', { name: '历史版本', exact: true }).waitFor({ state: 'hidden' });
  const restored = await api('entry/writer'); assert.equal(restored.value.title, '编辑功能专项'); assert.equal(restored.value.document.source, '编辑器正文，链接到官网。'); assert.equal(restored.value.status, 'draft');
  await visitor.reload(); assert.equal(await visitor.locator('main table tr').count(), 3);
  evidence.revisions = { sourceAndPageComparison: true, restoredToNewDraft: restored.revision > merged.revision, publicVersionPreserved: true };
  await visitor.close(); return evidence;
}
